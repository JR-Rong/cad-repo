#!/usr/bin/env python3
"""Turn one wave intake into project trees bound to a frozen family core.

The intake JSON (from emit_members.py) is the contract: one row per part,
with family key and topo_signature. This writes, for each part:

  <cadRoot>/projects/<pid>/project.yml   family, variant, expected core sha
  <cadRoot>/projects/<pid>/design.md     topo signature the builder must realise
  <cadRoot>/projects/<pid>/build.py      loads the frozen core and checks its sha

It does not run FreeCAD and does not copy geometry. The core itself comes
from family_src/<machine>/ via tools/family_freeze.py. A family with no
binding.json entry is still scaffolded, and build.py refuses to model
until the binding exists — a missing core is not a silent import of
whatever happens to sit on sys.path.

Existing build.py / design.md / project.yml are left in place unless
--force is given, so a re-run does not wipe a part the owner has edited.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import family_freeze  # noqa: E402


BUILD_PY = '''"""Load the frozen family core. Generated by tools/scaffold_wave.py.

The core file is the drawing this part is expanded from. Its sha256 is
pinned in project.yml from family_src/<machine>/MANIFEST.json. A live
edit of the core during a wave fails here instead of silently changing
geometry that the ledger will later treat as the same source.
"""
import hashlib
import importlib.util
import os


def _sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _core_path(root, module):
    live = os.path.join(root, "family", module)
    if os.path.isfile(live):
        return live
    alt = os.environ.get("CADKIT_FAMILY_SRC")
    if alt:
        cand = os.path.join(os.path.expanduser(alt), module)
        if os.path.isfile(cand):
            return cand
    return live


def build(b, proj):
    module = proj.field("family_module") or ""
    expect = proj.field("family_sha256") or ""
    if not module:
        raise RuntimeError(
            "project.yml has no family_module — fill family_src/%s/binding.json "
            "and re-run scaffold_wave.py --force for this family"
            % (proj.field("machine") or "?"))
    root = os.environ.get("CADKIT_ROOT") or os.path.abspath(
        os.path.join(proj.root, os.pardir, os.pardir))
    path = _core_path(root, module)
    if not os.path.isfile(path):
        raise RuntimeError("family core missing: %s" % path)
    got = _sha(path)
    if not expect:
        raise RuntimeError(
            "family core %s is not frozen (no sha in project.yml); "
            "run tools/family_freeze.py before building" % path)
    if got != expect:
        raise RuntimeError(
            "family core hash mismatch for %s: live %s frozen %s"
            % (module, got[:16], expect[:16]))
    spec = importlib.util.spec_from_file_location("family_core", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if not hasattr(mod, "build"):
        raise RuntimeError(
            "family core %s must define build(b, proj) — the production "
            "chain has no second driver" % path)
    return mod.build(b, proj)
'''


def _write_new(path, text, force):
    if os.path.exists(path) and not force:
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return True


def design_md(row):
    sig = row.get("topo_signature") or ""
    return """# %s

物件：%s
族谱：%s
拓扑签名（必须落成具体特征，禁止整模等比缩放）：`%s`

## 特征数
在开工前把签名里的每一条轴写成「有/无、条数、孔径」。尺寸档 `%s` 只是次要属性。

## 来源
由族谱核展开，不是逆向扫描。核文件与 sha256 见 project.yml 的 family_module / family_sha256。
""" % (row.get("project_id"), row.get("title") or "", row.get("family") or "",
       sig, row.get("size") or "")


def project_doc(row, machine, binding):
    doc = {
        "project_id": row["project_id"],
        "project_name": row.get("title") or row["project_id"],
        "description": row.get("title") or "",
        "unit": row.get("unit") or "mm",
        "type": row.get("type") or "part",
        "target_grade": row.get("grade") or "A",
        "author": "cad-fleet",
        "source_url": "internal",
        "license": "internal",
        "series": row.get("family") or "",
        "family": row.get("family") or "",
        "machine": machine,
        "wave": row.get("wave"),
        "variant": {
            "params": {"size": row.get("size")},
            "topo": {"signature": row.get("topo_signature")},
        },
        "waivers": ["internal"],
    }
    if binding:
        doc["family_module"] = binding["module"]
        if binding.get("sha256"):
            doc["family_sha256"] = binding["sha256"]
    return doc


def scaffold(intake_path, root, machine, repo=REPO, force=False, limit=None):
    doc = json.load(open(intake_path, encoding="utf-8"))
    rows = list(doc.get("detail") or [])
    if not rows:
        raise SystemExit("intake has no detail rows: %s" % intake_path)
    if limit:
        rows = rows[:limit]
    made = 0
    skipped = 0
    unbound = []
    for row in rows:
        pid = row["project_id"]
        fam = row.get("family") or ""
        binding = family_freeze.binding_for(machine, fam, repo)
        if binding is None and fam not in unbound:
            unbound.append(fam)
        base = os.path.join(root, "projects", pid)
        yml = os.path.join(base, "project.yml")
        wrote = _write_new(
            yml, json.dumps(project_doc(row, machine, binding),
                            ensure_ascii=False, indent=1) + "\n", force)
        _write_new(os.path.join(base, "design.md"), design_md(row), force)
        _write_new(os.path.join(base, "build.py"), BUILD_PY, force)
        if wrote:
            made += 1
        else:
            skipped += 1
    batch = doc.get("batch")
    if batch and doc.get("parts"):
        bdir = os.path.join(root, "batches")
        os.makedirs(bdir, exist_ok=True)
        bpath = os.path.join(bdir, batch + ".json")
        if force or not os.path.exists(bpath):
            with open(bpath, "w", encoding="utf-8") as f:
                json.dump({"batch": batch, "buyer": "internal",
                           "parts": doc["parts"]}, f, ensure_ascii=False, indent=1)
    return {"wrote": made, "kept": skipped, "unbound_families": unbound,
            "parts": len(rows)}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--intake", required=True)
    ap.add_argument("--root", required=True, help="cadRoot, e.g. ~/cad-fleet")
    ap.add_argument("--machine", required=True)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--limit", type=int, default=None)
    a = ap.parse_args()
    root = os.path.abspath(os.path.expanduser(a.root))
    info = scaffold(a.intake, root, a.machine.upper(), force=a.force, limit=a.limit)
    print("scaffold %s: wrote %d, kept %d, unbound families %s" % (
        root, info["wrote"], info["kept"],
        ",".join(info["unbound_families"]) or "-"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
